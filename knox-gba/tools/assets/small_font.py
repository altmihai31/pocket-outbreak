def build_small_font():
    widths = []
    rows = []
    for code in range(32, 97):
        glyph = GLYPHS.get(chr(code), GLYPHS['?'])
        assert len(glyph) == 5 and all(len(r) == len(glyph[0]) for r in glyph), chr(code)
        width = len(glyph[0])
        widths.append(width)
        masks = []
        for r in glyph:
            value = 0
            for i, c in enumerate(r):
                if c == '#':
                    value |= 0x80 >> i
            masks.append(value)
        rows.append(masks)

    lines = ['#include <cstdint>', '', 'namespace kx::small_font', '{', '',
             '// Silkscreen-style 5 px capitals for ASCII 32..96 (lower case maps to capitals, "`" is a middle dot).',
             'constexpr int height = 5;', 'constexpr int spacing = 1;', 'constexpr int first = 32;',
             'constexpr int count = %d;' % len(widths), '',
             'constexpr uint8_t widths[] = { %s };' % ', '.join(str(w) for w in widths), '',
             '// Five rows per glyph as 4bpp pixel masks (0xF per lit pixel, the leftmost in the low nibble).',
             'constexpr uint32_t rows[][5] = {']
    for code, masks in zip(range(32, 97), rows):
        nibbles = []
        for m in masks:
            value = 0
            for i in range(8):
                if m & (0x80 >> i):
                    value |= 0xF << (i * 4)
            nibbles.append(value)
        lines.append('    { %s },   // %s' % (', '.join('0x%05X' % m for m in nibbles), repr(chr(code))))
    lines += ['};', '', '}']
    write_header('kx_small_font.h', lines)
