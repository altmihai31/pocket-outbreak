"""Shared helpers for the asset generators."""
import io
import json
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GRAPHICS = os.path.join(ROOT, 'graphics')
INCLUDE = os.path.join(ROOT, 'include')
AUDIO = os.path.join(ROOT, 'audio')
BUTANO_COMMON_GRAPHICS = os.path.join(ROOT, '..', 'butano', 'common', 'graphics')

TRANSPARENT = (255, 0, 255)


def hexc(value):
    value = value.lstrip('#')
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def write_if_changed(path, data):
    if os.path.exists(path):
        with open(path, 'rb') as f:
            if f.read() == data:
                return
    with open(path, 'wb') as f:
        f.write(data)
    print('gen_assets: wrote ' + os.path.relpath(path, ROOT))


def save_bmp(name, pixels_rows, palette, info):
    """pixels_rows: list of rows of palette indices. palette: list of RGB tuples (16 or 32)."""
    height = len(pixels_rows)
    width = len(pixels_rows[0])
    im = Image.new('P', (width, height))
    if len(palette) > 16:
        palette = palette + [(0, 0, 0)] * (256 - len(palette))  # Butano wants 256 entries past 16
    flat = []
    for c in palette:
        flat.extend(c)
    im.putpalette(flat)
    im.putdata([p for row in pixels_rows for p in row])
    buf = io.BytesIO()
    im.save(buf, format='BMP')
    write_if_changed(os.path.join(GRAPHICS, name + '.bmp'), buf.getvalue())
    write_if_changed(os.path.join(GRAPHICS, name + '.json'),
                     (json.dumps(info, indent=4) + '\n').encode())


def blank(w, h, value=0):
    return [[value] * w for _ in range(h)]


def stack_tiles_8x8(tiles):
    """tiles: list of 8x8 index grids -> one 8-px-wide column image."""
    rows = []
    for t in tiles:
        rows.extend(t)
    return rows


def split_16(grid):
    """16x16 grid -> 4 hardware tiles in TL, TR, BL, BR order."""
    out = []
    for oy in (0, 8):
        for ox in (0, 8):
            out.append([row[ox:ox + 8] for row in grid[oy:oy + 8]])
    return out



def overlay(base, top, transparent=0):
    return [[t if t != transparent else b for b, t in zip(rb, rt)] for rb, rt in zip(base, top)]


def write_header(file_name, lines):
    guard = file_name.upper().replace('.', '_')
    text = ['// Generated by tools/gen_assets.py; do not edit.', '#ifndef ' + guard, '#define ' + guard, '']
    text += lines + ['', '#endif', '']
    write_if_changed(os.path.join(INCLUDE, file_name), chr(10).join(text).encode())
